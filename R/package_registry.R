#' Generate a Package's tsflow Registry
#'
#' Add `@tsflow transform` to functions that pipelines may call, and
#' `@tsflow hook binary_op` or `@tsflow hook postprocess` to evaluation hooks.
#' Enable this roclet in the package's `DESCRIPTION`:
#'
#' ```
#' Roxygen: list(packages = "tsflow",
#'   roclets = c("collate", "namespace", "rd", "tsflow::registry_roclet"))
#' ```
#'
#' Running `roxygen2::roxygenise()` (or `devtools::document()`) then generates
#' `inst/tsflow/registry.yml`.
#' Tagged functions need not be exported. Registries remain explicit: untagged
#' functions are never exposed to pipelines by [package_registry()].
#'
#' @return A roxygen2 roclet.
#' @export
registry_roclet <- function() {
  require_setup_package("roxygen2")
  roxygen2::roclet("tsflow_registry")
}

#' @exportS3Method roxygen2::roxy_tag_parse
roxy_tag_parse.roxy_tag_tsflow <- function(x) {
  words <- strsplit(trimws(x$raw), "[[:space:]]+")[[1L]]
  if (identical(words, "transform")) {
    x$val <- list(kind = "transforms")
  } else if (length(words) == 2L && words[[1L]] == "hook" &&
             words[[2L]] %in% c("binary_op", "postprocess")) {
    x$val <- list(kind = "hooks", slot = words[[2L]])
  } else {
    fail("`@tsflow` must be `transform`, `hook binary_op`, or `hook postprocess`")
  }
  x
}

# The tag is consumed by our registry roclet, not by the Rd roclet.
#' @exportS3Method roxygen2::roxy_tag_rd
roxy_tag_rd.roxy_tag_tsflow <- function(x, base_path, env) NULL

#' @exportS3Method roxygen2::roclet_process
roclet_process.roclet_tsflow_registry <- function(x, blocks, env, base_path) {
  registry <- list(version = 1L, transforms = list(), hooks = list())
  for (block in blocks) {
    tags <- Filter(function(tag) identical(tag$tag, "tsflow"), block$tags)
    if (length(tags) == 0L) next
    if (!inherits(block$object, "function")) {
      fail("`@tsflow` tags must document a function")
    }
    name <- block$object$alias
    for (tag in tags) {
      kind <- tag$val$kind
      key <- tag$val$slot %||% name
      if (key %in% names(registry[[kind]])) {
        fail(sprintf("duplicate tsflow %s registration `%s`", kind, key))
      }
      registry[[kind]][[key]] <- name
    }
  }
  registry$transforms <- registry$transforms[sort(names(registry$transforms))]
  registry$hooks <- registry$hooks[sort(names(registry$hooks))]
  registry
}

#' @exportS3Method roxygen2::roclet_output
roclet_output.roclet_tsflow_registry <- function(x, results, base_path, ...) {
  path <- file.path(base_path, "inst", "tsflow", "registry.yml")
  header <- "# Generated by tsflow::registry_roclet(); do not edit by hand."
  if (file.exists(path) && !identical(readLines(path, n = 1L, warn = FALSE), header)) {
    fail(sprintf("refusing to overwrite a registry not generated by tsflow: %s", path))
  }
  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
  writeLines(c(header, yaml::as.yaml(results)), path, useBytes = TRUE)
  invisible(path)
}

#' Read a Package's tsflow Registry
#'
#' Reads the registry generated by [registry_roclet()] and resolves only its
#' tagged functions from the package namespace, including unexported functions.
#' Works with installed packages and packages loaded by `pkgload::load_all()`.
#'
#' @param pkg A single package name.
#' @return A list with named lists `transforms` and `hooks`, ready to pass to
#'   [plan_pipeline()], [execute_pipeline()], or [tar_tsflow()].
#' @export
package_registry <- function(pkg) {
  if (!is_scalar_string(pkg) || !nzchar(pkg)) fail("`pkg` must be a single package name")
  if (!requireNamespace(pkg, quietly = TRUE)) {
    fail(sprintf("package `%s` is not installed or loaded", pkg))
  }
  # An installed tsflow does not receive pkgload's system.file() shim for the
  # package being developed. Resolve its source-tree inst/ directory explicitly.
  development <- "pkgload" %in% loadedNamespaces() && pkgload::is_dev_package(pkg)
  path <- if (development) {
    file.path(getNamespaceInfo(pkg, "path"), "inst", "tsflow", "registry.yml")
  } else {
    system.file("tsflow", "registry.yml", package = pkg)
  }
  if (!nzchar(path) || !file.exists(path)) {
    fail(sprintf("package `%s` has no tsflow registry; run `roxygen2::roxygenise()` with `tsflow::registry_roclet` enabled", pkg))
  }
  registry <- yaml::read_yaml(path)
  if (!is.list(registry) || !identical(registry$version, 1L)) {
    fail(sprintf("package `%s` has an unsupported tsflow registry format", pkg))
  }
  ns <- asNamespace(pkg)
  resolve_entries <- function(entries) {
    if (!is.list(entries) || (length(entries) > 0L &&
        (is.null(names(entries)) || anyNA(names(entries)) || any(!nzchar(names(entries))) ||
         anyDuplicated(names(entries))))) {
      fail(sprintf("package `%s` has an invalid tsflow registry", pkg))
    }
    lapply(entries, function(name) {
      if (!is_scalar_string(name) || !exists(name, envir = ns, inherits = FALSE) ||
          !is.function(get(name, envir = ns, inherits = FALSE))) {
        fail(sprintf("package `%s` has a stale tsflow registry; regenerate it with `roxygen2::roxygenise()`", pkg))
      }
      get(name, envir = ns, inherits = FALSE)
    })
  }
  runtime <- list(
    transforms = resolve_entries(registry$transforms),
    hooks = resolve_entries(registry$hooks)
  )
  new_runtime(runtime$transforms, runtime$hooks)
}
